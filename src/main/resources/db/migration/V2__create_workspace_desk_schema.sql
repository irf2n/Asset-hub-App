-- 1. PARENT TABLE: Workspaces
CREATE TABLE workspaces(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  floor_number INT NOT NULL,
  building VARCHAR(100) NOT NULL
);

-- 2. CHILD TABLE: Desks (references workspaces)

CREATE TABLE desks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  desk_code VARCHAR(50) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL,
  workspace_id BIGINT NOT NULL,
  CONSTRAINT fk_desks_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces(id)
);


-- 3. LEDGER TABLE , Desk Allocations (links to users and desks)

CREATE TABLE desk_allocations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  desk_id BIGINT NOT NULL,
  allocation_date DATE NOT NULL,
  release_date DATE,
  status VARCHAR(20) NOT NULL,
  notes VARCHAR(255),
  CONSTRAINT fk_desk_allocations_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_desk_allocations_desk FOREIGN KEY (desk_id) REFERENCES desks(id)
);