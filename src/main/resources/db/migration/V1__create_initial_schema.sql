-- 1. Create departments table
CREATE TABLE departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    code VARCHAR(20) NOT NULL UNIQUE
);

-- 2. Create users table (references departments plural)
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    role VARCHAR(30) NOT NULL,
    department_id BIGINT NOT NULL,
    CONSTRAINT fk_users_department FOREIGN KEY (department_id) REFERENCES departments(id)
);

-- 3. Create asset categories table
CREATE TABLE asset_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255)
);

-- 4. Create assets table (references asset_categories plural)
CREATE TABLE assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_number VARCHAR(100) NOT NULL UNIQUE,
    model_name VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL,
    category_id BIGINT NOT NULL,
    CONSTRAINT fk_assets_category FOREIGN KEY (category_id) REFERENCES asset_categories(id)
);

-- 5. Create asset allocations table (references users and assets)
CREATE TABLE asset_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    allocation_date DATE NOT NULL,
    return_date DATE,
    status VARCHAR(20) NOT NULL,
    notes VARCHAR(255),
    CONSTRAINT fk_allocations_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_allocations_asset FOREIGN KEY (asset_id) REFERENCES assets(id)
);